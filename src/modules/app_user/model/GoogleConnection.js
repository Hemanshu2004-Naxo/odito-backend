  google_ads_keyword_sync_completed_at: { type: Date, default: null },
  google_ads_keyword_sync_failed_at: { type: Date, default: null },
  google_ads_keyword_sync_error: { type: String, default: null },
  google_ads_keyword_sync_duration_ms: { type: Number, default: null },
